#!/usr/bin/env python3
"""Public API of the release must survive on the working branch (#2751 family C).

A semver hotfix merged on main (e.g. restoring `pub mod simd_neon_prefetch`
in 8.2.0) that never reaches develop shows up at the next back-merge — and a
plain merge can even keep the `pub(crate)` side SILENTLY, with no conflict
marker, because only one side edited the declaration line. That is exactly
what happened to lib.rs in #2749, caught only because clippy's dead_code
failed the pre-commit hook.

Two comparison modes:

  * default (snapshot): compares the tree against
    scripts/public-api-snapshot.txt, the public items of the last release,
    regenerated by `--write-snapshot` and committed with the release on
    main (the back-merge carries it over). Refuses any snapshot item that
    is missing or `pub(crate)` in the tree. This mode is what the refusal
    vectors run.
  * --base REF (git): same comparison between REF and HEAD. In CI the lint
    job uses origin/main, which fetch-depth: 0 guarantees present.

Deliberate removals belong in scripts/pub-parity-allowlist.txt
(one `path item-kind name` per line).
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

PUB_ITEM_RE = re.compile(
    r"^\s*pub\s+(fn|mod|struct|enum|trait|type|const|static)\s+([A-Za-z_][A-Za-z0-9_]*)"
)
PUB_CRATE_ITEM_RE = re.compile(
    r"^\s*pub\(crate\)\s+(fn|mod|struct|enum|trait|type|const|static)\s+([A-Za-z_][A-Za-z0-9_]*)"
)
SNAPSHOT = Path("scripts/public-api-snapshot.txt")
ALLOWLIST = Path("scripts/pub-parity-allowlist.txt")

#: Binary crates: their `pub` items are not a published API surface.
BINARY_CRATES = ("velesdb-cli", "velesdb-mobile")


def is_library_source(rel: str) -> bool:
    parts = rel.split("/")
    return len(parts) > 1 and parts[0] == "crates" and parts[1] not in BINARY_CRATES and "/src/" in rel


def _git(root: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(root), *args], capture_output=True, text=True, check=True
    ).stdout


def _git_show(root: Path, ref: str, path: str) -> str:
    proc = subprocess.run(
        ["git", "-C", str(root), "show", f"{ref}:{path}"],
        capture_output=True,
        text=True,
    )
    return proc.stdout if proc.returncode == 0 else ""


def pub_items_of_text(text: str) -> set[tuple[str, str]]:
    found: set[tuple[str, str]] = set()
    for line in text.splitlines():
        m = PUB_ITEM_RE.match(line)
        if m:
            found.add((m.group(1), m.group(2)))
    return found


def pub_crate_items_of_text(text: str) -> set[tuple[str, str]]:
    found: set[tuple[str, str]] = set()
    for line in text.splitlines():
        m = PUB_CRATE_ITEM_RE.match(line)
        if m:
            found.add((m.group(1), m.group(2)))
    return found


def load_triple_list(path: Path) -> set[tuple[str, str, str]]:
    entries: set[tuple[str, str, str]] = set()
    if not path.exists():
        return entries
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) != 3:
            raise ValueError(f"{path}: malformed line (want 'path kind name'): {line!r}")
        entries.add((parts[0], parts[1], parts[2]))
    return entries


def scan_tree(root: Path) -> dict[str, tuple[set[tuple[str, str]], set[tuple[str, str]]]]:
    """path -> (pub items, pub(crate) items) for every crates/**/src .rs file."""
    out: dict[str, tuple[set[tuple[str, str]], set[tuple[str, str]]]] = {}
    for path in sorted(root.glob("crates/*/src/**/*.rs")):
        rel = str(path.relative_to(root)).replace("\\", "/")
        if not is_library_source(rel):
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        out[rel] = (pub_items_of_text(text), pub_crate_items_of_text(text))
    return out


def write_snapshot(root: Path) -> int:
    lines = ["# Public API snapshot of the last release — regenerate with --write-snapshot."]
    for rel, (pubs, _) in sorted(scan_tree(root).items()):
        for kind, name in sorted(pubs):
            lines.append(f"{rel} {kind} {name}")
    (root / SNAPSHOT).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {SNAPSHOT} ({len(lines) - 1} items)")
    return 0


def snapshot_violations(root: Path) -> list[str]:
    snapshot = load_triple_list(root / SNAPSHOT)
    if not snapshot:
        return []
    allow = load_triple_list(root / ALLOWLIST)
    tree = scan_tree(root)
    violations: list[str] = []
    for rel, kind, name in sorted(snapshot):
        if (rel, kind, name) in allow:
            continue
        pubs, pub_crates = tree.get(rel, (set(), set()))
        if (kind, name) in pubs:
            continue
        if (kind, name) in pub_crates:
            violations.append(
                f"{rel}: `pub {kind} {name}` in the release snapshot is `pub(crate)` here — "
                "a semver break; forward-port the release fix or allowlist it"
            )
        else:
            violations.append(
                f"{rel}: `pub {kind} {name}` in the release snapshot is missing here — "
                "a semver break; forward-port the release fix or allowlist it"
            )
    return violations


def parity_violations(root: Path, base: str) -> list[str]:
    violations: list[str] = []
    allow = load_triple_list(root / ALLOWLIST)
    rs_files = _git(root, "ls-files", "--", "crates").splitlines()
    rs_files = [f for f in rs_files if f.endswith(".rs") and is_library_source(f)]
    for rel in rs_files:
        base_text = _git_show(root, base, rel)
        head_text = _git_show(root, "HEAD", rel)
        if not base_text:
            continue
        base_pub = pub_items_of_text(base_text)
        head_pub = pub_items_of_text(head_text)
        head_pub_crate = pub_crate_items_of_text(head_text)
        for kind, name in sorted(base_pub - head_pub):
            if (rel, kind, name) in allow:
                continue
            if (kind, name) in head_pub_crate:
                violations.append(
                    f"{rel}: `pub {kind} {name}` on {base} is `pub(crate)` on HEAD — "
                    "a semver break; forward-port the release fix or allowlist it"
                )
            else:
                violations.append(
                    f"{rel}: `pub {kind} {name}` present on {base} is missing on HEAD — "
                    "a semver break; forward-port the release fix or allowlist it"
                )
    return violations


def main(argv: "list[str] | None" = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", default=".", help="Repository root (default: cwd)")
    parser.add_argument(
        "--base",
        default=None,
        help="Git ref holding the published public API (in CI: origin/main); "
        "without it the committed snapshot is used",
    )
    parser.add_argument(
        "--write-snapshot",
        action="store_true",
        help="Regenerate scripts/public-api-snapshot.txt from the current tree",
    )
    args = parser.parse_args(argv)

    root = Path(args.root).resolve()
    if args.write_snapshot:
        return write_snapshot(root)

    violations: list[str] = []
    if args.base:
        try:
            violations = parity_violations(root, args.base)
        except (subprocess.CalledProcessError, ValueError) as exc:
            print(f"FAILED: public-API parity check errored: {exc}", file=sys.stderr)
            return 2
    else:
        try:
            violations = snapshot_violations(root)
        except ValueError as exc:
            print(f"FAILED: {exc}", file=sys.stderr)
            return 2

    if violations:
        print("FAILED: public API regressions vs the release snapshot:")
        for v in violations:
            print(f"  - {v}")
        return 1
    print("PASSED: public API parity with the release holds.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
